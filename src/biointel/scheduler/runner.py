"""BioIntel Scheduler and Automation Engine.

Manages daily incremental discovery, weekly comparative digests,
and generates macOS launchd daemon configuration plists.
"""

from __future__ import annotations

import plistlib
import sys
from datetime import datetime, timezone
from pathlib import Path
from typing import Dict, Optional
from biointel.comparison.matrix import TechnologyComparator
from biointel.discovery.crawler import DiscoveryCrawler
from biointel.reports.export import ResearchExporter
from biointel.reports.memo_generator import DiligenceMemoGenerator
from biointel.storage.database import Database


class BioIntelScheduler:
    """Orchestrates scheduled discovery cycles and launchd plist generation."""

    def __init__(self, db: Database, base_dir: Optional[str | Path] = None) -> None:
        self.db = db
        if base_dir:
            self.base_dir = Path(base_dir)
        else:
            self.base_dir = Path(__file__).parent.parent.parent.parent

    def run_daily_job(self, mode: str = "offline") -> Dict[str, str]:
        """Execute daily discovery and evidence audit."""
        crawler = DiscoveryCrawler(self.db)
        report = crawler.run_discovery_pipeline(mode=mode)
        return {
            "status": "success",
            "run_id": report.run_id,
            "summary": report.summary_markdown,
        }

    def run_weekly_digest(self) -> Path:
        """Run weekly competitive comparison and produce Markdown innovation digest."""
        comparator = TechnologyComparator(self.db)
        comp = comparator.generate_gene_editing_comparison()

        memo_gen = DiligenceMemoGenerator(self.db)
        memo = memo_gen.generate_gene_editing_memo(save_file=True)

        exporter = ResearchExporter(self.db)
        archive_path = exporter.export_full_archive("weekly_snapshot")

        digest_file = self.base_dir / "outputs" / "research" / "weekly_innovation_digest.md"
        digest_file.parent.mkdir(parents=True, exist_ok=True)

        now_str = datetime.now(timezone.utc).strftime("%Y-%m-%d")
        digest_content = f"""# BioIntel Weekly Biotechnology Innovation Digest — {now_str}
**Autonomous Intelligence & Commercialization Synthesis**

## 1. Key Competitive Synthesis
- **Active Focus:** CRISPR-Cas9 DSB Nuclease vs. Prime Editing Platforms.
- **Critical Caveat:** {comp.incompatibility_warnings[0] if comp.incompatibility_warnings else 'No condition warnings.'}
- **Strategic Takeaway:** {comp.strategic_takeaway}

## 2. Commercialization & Techno-Economic Tracking
- **Precision Fermentation:** Unit cost model established for engineered stereoselective hydrolases ($14.20/kg at 45 g/L titer).
- **Deliverables:** Structured research archive updated at `{archive_path.name}`.

*Notice: Generated by BioIntel local scheduler.*
"""
        digest_file.write_text(digest_content, encoding="utf-8")
        return digest_file

    def generate_launchd_plist(
        self,
        plist_destination: Optional[str | Path] = None,
        hour: int = 4,
        minute: int = 0,
    ) -> Path:
        """
        Generate macOS launchd plist for automated daily execution.
        Note: Jobs cannot execute while macOS is asleep or powered off;
        launchd will execute upon wake if missed.
        """
        dest = Path(plist_destination) if plist_destination else self.base_dir / "config" / "com.biointel.daily.plist"
        dest.parent.mkdir(parents=True, exist_ok=True)

        python_bin = sys.executable
        cli_script = str(self.base_dir / "src" / "biointel" / "cli.py")

        plist_data = {
            "Label": "com.biointel.daily",
            "ProgramArguments": [
                python_bin,
                cli_script,
                "discover",
                "--offline",
            ],
            "StartCalendarInterval": {
                "Hour": hour,
                "Minute": minute,
            },
            "StandardOutPath": str(self.base_dir / "outputs" / "launchd_stdout.log"),
            "StandardErrorPath": str(self.base_dir / "outputs" / "launchd_stderr.log"),
            "WorkingDirectory": str(self.base_dir),
            "RunAtLoad": False,
        }

        with open(dest, "wb") as f:
            plistlib.dump(plist_data, f)

        return dest
